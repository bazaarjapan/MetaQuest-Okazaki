(async () => {
  const results=[], s=()=>window.__okazaki.getState(), wait=ms=>new Promise(r=>setTimeout(r,ms));
  const check=(ok,name)=>{results.push({ok:!!ok,name});if(!ok)throw Error(name);};
  const until=async fn=>{const end=performance.now()+10000;while(!fn()&&performance.now()<end)await wait(50);
    if(!fn())throw Error(JSON.stringify({last:results.at(-1),creative:s().creative,avatar:s().avatar}));check(true,"frame-settled");};
  const key=(code,type="keydown")=>window.dispatchEvent(new KeyboardEvent(type,{code,bubbles:true,cancelable:true}));
  const canvas=document.querySelector("#viewport > canvas");
  check(s().ready&&s().creative.mode==="creative","creative-ready");
  if(s().ui.open)document.querySelector("#panel-close").click();
  if(!s().free)document.querySelector("#free-move").click();canvas.focus();
  await until(()=>s().creative.enabled&&!s().creative.blocked);
  key("KeyZ","keyup");key("KeyX");key("KeyX","keyup");
  await until(()=>!s().creative.wingFlight);
  key("KeyW");await until(()=>s().avatar.animation==="walk");check(s().avatar.animation==="walk","walking");
  key("ControlLeft");await until(()=>s().avatar.animation==="run");check(s().avatar.animation==="run","running");
  key("KeyW","keyup");key("ControlLeft","keyup");await until(()=>s().avatar.animation==="idle");check(s().avatar.animation==="idle","stationary");
  const start=s().creative.anchor;key("KeyZ");await until(()=>s().avatar.boosting&&s().creative.wingSpeed>12);
  check(s().avatar.wingsOpen&&s().creative.wingFlight,"rocket-wings-open");
  check(s().creative.anchor.some((v,i)=>Math.abs(v-start[i])>.01),"actual-flight");
  const heading=s().creative.yaw, pitch=s().creative.pitch;
  canvas.dispatchEvent(new PointerEvent("pointerdown",{pointerType:"mouse",button:0,buttons:1,pointerId:77,clientX:300,clientY:300,bubbles:true,cancelable:true}));
  canvas.dispatchEvent(new PointerEvent("pointermove",{pointerType:"mouse",buttons:1,pointerId:77,clientX:380,clientY:260,bubbles:true}));
  window.dispatchEvent(new PointerEvent("pointerup",{pointerId:77,button:0,clientX:380,clientY:260,bubbles:true}));
  check(s().creative.yaw<heading&&s().creative.pitch>pitch,"unlocked-flight-mouse-steers");
  canvas.dispatchEvent(new MouseEvent("click",{bubbles:true}));
  check(s().creative.wingFlight,"steering-click-does-not-cancel-flight");
  const boostHeight=s().creative.anchor[1];key("Space");
  await until(()=>s().creative.anchor[1]>boostHeight+.1);check(s().avatar.boosting,"Space-climbs-during-boost");key("Space","keyup");
  key("KeyZ","keyup");await until(()=>s().avatar.animation==="glide");check(!s().avatar.boosting&&s().avatar.wingsOpen,"release-glides-without-flame");
  const glideHeight=s().creative.anchor[1];key("Space");
  await until(()=>s().creative.anchor[1]>glideHeight+.1);check(s().creative.wingFlight,"Space-climbs-during-glide");key("Space","keyup");
  key("KeyX");key("KeyX","keyup");await until(()=>s().avatar.animation==="idle");
  const stopped=JSON.stringify(s().creative.anchor);await wait(150);
  check(JSON.stringify(s().creative.anchor)===stopped&&!s().creative.wingFlight,"X-stops-flight");
  key("KeyZ");await until(()=>s().creative.wingFlight);window.dispatchEvent(new Event("blur"));
  await until(()=>!s().creative.wingFlight);check(!s().avatar.boosting,"focus-loss-clears-rocket");
  check(document.querySelector("#creative-help").textContent.includes("Z長押し"),"instructions-present");
  return {passed:true,results};
})();
